String _tight(String name) =>
    name.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]'), '');

const _filler = [
  'bank', 'plc', 'limited', 'ltd', 'nigeria', 'nig', 'microfinance', 'mfb',
  'digital', 'services', 'service', 'company', 'of', 'for', 'the', 'and',
];

String _loose(String name) {
  var s = name.toLowerCase();
  for (final w in _filler) {
    s = s.replaceAll(RegExp('\\b$w\\b'), ' ');
  }
  return s.replaceAll(RegExp(r'[^a-z0-9]'), '');
}

/// The asset for a bank, or null when none is bundled — callers fall back to
/// the lettered badge.
///
/// The code is tried first because it is exact, but it cannot be relied on:
/// banks carry both a CBN sort code and a NIP code, and which one an endpoint
/// returns varies. The name tables are the backstop.
String? bankLogoAsset({String? code, String? name}) {
  final c = (code ?? '').trim();
  if (c.isNotEmpty) {
    for (final candidate in <String>{
      c,
      c.toUpperCase(),
      c.replaceFirst(RegExp(r'^0+'), ''),
      c.padLeft(3, '0'),
    }) {
      if (_codes.contains(candidate)) {
        return 'assets/images/banks/$candidate.png';
      }
    }
    // Some sources pad codes differently, so compare without leading zeros.
    final bare = c.replaceFirst(RegExp(r'^0+'), '');
    if (bare.isNotEmpty) {
      for (final known in _codes) {
        if (known.replaceFirst(RegExp(r'^0+'), '') == bare) {
          return 'assets/images/banks/$known.png';
        }
      }
    }
  }

  final n = name ?? '';
  if (n.trim().isEmpty) return null;
  final t = _tight(n);
  final l = _loose(n);

  for (final key in [t, l]) {
    if (key.length < 3) continue;
    final hit = _byTight[key] ?? _byLoose[key];
    if (hit != null) return 'assets/images/banks/$hit.png';
  }

  // Nothing exact: take the longest key the name contains, so "Guaranty Trust
  // Bank Plc (GTB)" still resolves without matching every three-letter stem.
  String? best;
  var bestLen = 0;
  for (final table in [_byTight, _byLoose]) {
    for (final entry in table.entries) {
      final k = entry.key;
      if (k.length <= bestLen || k.length < 8) continue;
      if (t.contains(k) || l.contains(k)) {
        best = entry.value;
        bestLen = k.length;
      }
    }
  }
  return best == null ? null : 'assets/images/banks/$best.png';
}
